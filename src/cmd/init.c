void cmd_init(void) {
    char cfgdir[MAX_PATH];   xdg_config_dir(cfgdir, sizeof(cfgdir));
    char cfgpath[MAX_PATH];  snprintf(cfgpath,  sizeof(cfgpath),  "%s/config.toml",   cfgdir);
    char tpldir[MAX_PATH];   snprintf(tpldir,   sizeof(tpldir),   "%s/templates",      cfgdir);
    char hookdir[MAX_PATH];  snprintf(hookdir,  sizeof(hookdir),  "%s/hooks",          cfgdir);
    char gtk4tpl[MAX_PATH];  snprintf(gtk4tpl,  sizeof(gtk4tpl),  "%s/gtk4.css",       tpldir);
    char gtk3tpl[MAX_PATH];  snprintf(gtk3tpl,  sizeof(gtk3tpl),  "%s/gtk3.css",       tpldir);
    char hookpath[MAX_PATH]; snprintf(hookpath, sizeof(hookpath), "%s/gtk-reload.sh",  hookdir);

    mkdirs_local(tpldir);
    mkdirs_local(hookdir);

    /* config.toml */
    if (access(cfgpath, F_OK) == 0) {
        printf("exists (skipping): %s\n", cfgpath);
    } else {
        write_file(cfgpath, GTK_CONFIG);
        printf("created: %s\n", cfgpath);
    }

    /* templates/gtk4.css */
    if (access(gtk4tpl, F_OK) == 0) {
        printf("exists (skipping): %s\n", gtk4tpl);
    } else {
        /* split across three string literals to stay within ISO C99 4095-char limit */
        size_t la  = strlen(GTK4_TEMPLATE_A),  la2 = strlen(GTK4_TEMPLATE_A2),
               lb  = strlen(GTK4_TEMPLATE_B),  lc  = strlen(GTK4_TEMPLATE_C);
        char *gtk4buf = malloc(la + la2 + lb + lc + 1);
        if (gtk4buf) {
            size_t off = 0;
            memcpy(gtk4buf + off, GTK4_TEMPLATE_A,  la);  off += la;
            memcpy(gtk4buf + off, GTK4_TEMPLATE_A2, la2); off += la2;
            memcpy(gtk4buf + off, GTK4_TEMPLATE_B,  lb);  off += lb;
            memcpy(gtk4buf + off, GTK4_TEMPLATE_C,  lc + 1);
            write_file(gtk4tpl, gtk4buf);
            free(gtk4buf);
        }
        printf("created: %s\n", gtk4tpl);
    }

    /* templates/gtk3.css */
    if (access(gtk3tpl, F_OK) == 0) {
        printf("exists (skipping): %s\n", gtk3tpl);
    } else {
        write_file(gtk3tpl, GTK3_TEMPLATE);
        printf("created: %s\n", gtk3tpl);
    }

    /* hooks/gtk-reload.sh */
    if (access(hookpath, F_OK) == 0) {
        printf("exists (skipping): %s\n", hookpath);
    } else {
        write_file(hookpath, GTK_RELOAD_HOOK);
        char cmd[MAX_PATH + 16];
        snprintf(cmd, sizeof(cmd), "chmod +x %s", hookpath);
        int r = system(cmd); (void)r;
        printf("created: %s\n", hookpath);
    }

    /* ensure GTK output dirs exist */
    const char *home = real_home();
    char gtk4dir[MAX_PATH]; snprintf(gtk4dir, sizeof(gtk4dir), "%s/.config/gtk-4.0", home);
    char gtk3dir[MAX_PATH]; snprintf(gtk3dir, sizeof(gtk3dir), "%s/.config/gtk-3.0", home);
    mkdirs_local(gtk4dir);
    mkdirs_local(gtk3dir);
    printf("ready:   %s\n", gtk4dir);
    printf("ready:   %s\n", gtk3dir);

    printf("\nQuick start:\n");
    printf("  mcugen color \"#6750A4\"              # light → gtk3 + gtk4\n");
    printf("  mcugen color \"#6750A4\" --mode dark  # dark scheme\n");
    printf("  mcugen image ~/Pictures/wall.jpg    # seed from wallpaper\n");
    printf("  mcugen blend \"#6750A4\" \"#1DB954\"    # blend two seeds\n");
    printf("  mcugen save mytheme                 # save profile\n");
    printf("  mcugen check                        # validate config\n");
    printf("\nHook: %s\n", hookpath);
    printf("Runs after every generation — reloads GTK3/GTK4/libadwaita apps live.\n");
}
