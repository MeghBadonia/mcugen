/* ── GTK reload hook ─────────────────────────────────────────────────────── */
static const char GTK_RELOAD_HOOK[] =
    "#!/bin/sh\n"
    "# mcugen GTK reload hook\n"
    "# Forces running GTK3/GTK4/libadwaita apps to re-read CSS by toggling\n"
    "# gsettings properties that apps watch via GtkSettings / AdwStyleManager.\n"
    "\n"
    "if command -v gsettings >/dev/null 2>&1; then\n"
    "    # Capture current values\n"
    "    _THEME=$(gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d \"'\")\n"
    "    _SCHEME=$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | tr -d \"'\")\n"
    "\n"
    "    # Toggle gtk-theme — triggers GtkSettings:notify::gtk-theme in GTK3/GTK4\n"
    "    gsettings set org.gnome.desktop.interface gtk-theme '' 2>/dev/null\n"
    "    gsettings set org.gnome.desktop.interface gtk-theme \"$_THEME\" 2>/dev/null\n"
    "\n"
    "    # Toggle color-scheme — triggers AdwStyleManager reload in libadwaita apps\n"
    "    if [ \"$_SCHEME\" = 'prefer-dark' ]; then\n"
    "        gsettings set org.gnome.desktop.interface color-scheme 'default' 2>/dev/null\n"
    "    else\n"
    "        gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' 2>/dev/null\n"
    "    fi\n"
    "    sleep 0.05\n"
    "    gsettings set org.gnome.desktop.interface color-scheme \"$_SCHEME\" 2>/dev/null\n"
    "fi\n"
    "\n"
    "# xdg-desktop-portal: nudge Settings portal so Flatpak apps pick up changes\n"
    "if command -v gdbus >/dev/null 2>&1; then\n"
    "    gdbus call --session \\\n"
    "        --dest org.freedesktop.portal.Desktop \\\n"
    "        --object-path /org/freedesktop/portal/desktop \\\n"
    "        --method org.freedesktop.DBus.Properties.GetAll \\\n"
    "        org.freedesktop.portal.Settings >/dev/null 2>&1 || true\n"
    "fi\n";

